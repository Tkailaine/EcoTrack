CREATE OR REPLACE TRIGGER TRG_ALERTA_RESIDUO
AFTER INSERT ON REGISTRO_DESCARTE
FOR EACH ROW
DECLARE
    TOTAL NUMBER;
    LIMITE NUMBER;
BEGIN
    SELECT SUM(RD.QUANTIDADE), R.LIMITE_MAX
    INTO TOTAL, LIMITE
    FROM REGISTRO_DESCARTE RD
    JOIN RESIDUO R ON RD.ID_RESIDUO = R.ID_RESIDUO
    WHERE RD.ID_RESIDUO = :NEW.ID_RESIDUO
    GROUP BY R.LIMITE_MAX;

    IF TOTAL > LIMITE THEN
        INSERT INTO ALERTA
        VALUES (SEQ_ALERTA.NEXTVAL,
                'Limite de resíduo ultrapassado para ID ' || :NEW.ID_RESIDUO,
                SYSDATE,
                'LIMITE_RESIDUO');
    END IF;
END;


CREATE OR REPLACE TRIGGER TRG_GERAR_COLETA
AFTER INSERT ON REGISTRO_DESCARTE
FOR EACH ROW
DECLARE
    TOTAL NUMBER;
    CAPACIDADE NUMBER;
    EXISTE NUMBER;
BEGIN
    SELECT SUM(RD.QUANTIDADE), P.CAPACIDADE_MAX
    INTO TOTAL, CAPACIDADE
    FROM REGISTRO_DESCARTE RD
    JOIN PONTO_COLETA P ON RD.ID_PONTO = P.ID_PONTO
    WHERE RD.ID_PONTO = :NEW.ID_PONTO
    GROUP BY P.CAPACIDADE_MAX;

    SELECT COUNT(*) INTO EXISTE
    FROM COLETA
    WHERE ID_PONTO = :NEW.ID_PONTO
      AND STATUS = 'PENDENTE';

    IF TOTAL >= CAPACIDADE AND EXISTE = 0 THEN
        INSERT INTO COLETA
        VALUES (SEQ_COLETA.NEXTVAL, :NEW.ID_PONTO, SYSDATE, 'PENDENTE');

        INSERT INTO ALERTA
        VALUES (SEQ_ALERTA.NEXTVAL,
                'Coleta gerada automaticamente para ponto ' || :NEW.ID_PONTO,
                SYSDATE,
                'GERACAO_COLETA');
    END IF;
END;


CREATE OR REPLACE TRIGGER TRG_STATUS_COLETA
BEFORE UPDATE ON COLETA
FOR EACH ROW
BEGIN
    IF :NEW.DATA_COLETA <= SYSDATE THEN
        :NEW.STATUS := 'REALIZADA';
    END IF;
END;


CREATE OR REPLACE TRIGGER TRG_BLOQUEIO_DESCARTE
BEFORE INSERT ON REGISTRO_DESCARTE
FOR EACH ROW
DECLARE
    CAPACIDADE NUMBER;
BEGIN
    SELECT CAPACIDADE_MAX INTO CAPACIDADE
    FROM PONTO_COLETA
    WHERE ID_PONTO = :NEW.ID_PONTO;

    IF :NEW.QUANTIDADE > CAPACIDADE THEN
        INSERT INTO ALERTA
        VALUES (SEQ_ALERTA.NEXTVAL,
                'Tentativa de descarte acima da capacidade no ponto ' || :NEW.ID_PONTO,
                SYSDATE,
                'ERRO_DESCARTE');

        RAISE_APPLICATION_ERROR(-20001, 'Erro: quantidade excede a capacidade do ponto.');
    END IF;
END;
