CREATE TABLE RESIDUO (
    ID_RESIDUO NUMBER PRIMARY KEY,
    TIPO VARCHAR2(50) NOT NULL,
    LIMITE_MAX NUMBER NOT NULL
);

CREATE TABLE PONTO_COLETA (
    ID_PONTO NUMBER PRIMARY KEY,
    LOCAL VARCHAR2(100) NOT NULL,
    CAPACIDADE_MAX NUMBER NOT NULL
);

CREATE TABLE COLETA (
    ID_COLETA NUMBER PRIMARY KEY,
    ID_PONTO NUMBER NOT NULL,
    DATA_COLETA DATE,
    STATUS VARCHAR2(20) CHECK (STATUS IN ('PENDENTE', 'REALIZADA')),
    CONSTRAINT FK_COLETA_PONTO FOREIGN KEY (ID_PONTO) REFERENCES PONTO_COLETA(ID_PONTO)
);

CREATE TABLE REGISTRO_DESCARTE (
    ID_DESCARTE NUMBER PRIMARY KEY,
    ID_RESIDUO NUMBER NOT NULL,
    ID_PONTO NUMBER NOT NULL,
    QUANTIDADE NUMBER NOT NULL,
    DATA_DESCARTE DATE DEFAULT SYSDATE,
    CONSTRAINT FK_DESC_RESIDUO FOREIGN KEY (ID_RESIDUO) REFERENCES RESIDUO(ID_RESIDUO),
    CONSTRAINT FK_DESC_PONTO FOREIGN KEY (ID_PONTO) REFERENCES PONTO_COLETA(ID_PONTO)
);

CREATE TABLE ALERTA (
    ID_ALERTA NUMBER PRIMARY KEY,
    MENSAGEM VARCHAR2(200),
    DATA_ALERTA DATE,
    TIPO_ALERTA VARCHAR2(50)
);

CREATE SEQUENCE SEQ_COLETA START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE SEQ_DESCARTE START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE SEQ_ALERTA START WITH 1 INCREMENT BY 1;
